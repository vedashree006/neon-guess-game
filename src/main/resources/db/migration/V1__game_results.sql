-- Baseline: the original leaderboard table (identical to the pre-analytics schema).
-- Idempotent on purpose, so existing databases keep their data.
CREATE TABLE IF NOT EXISTS game_results (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id       VARCHAR(36) NOT NULL,
    player_name   VARCHAR(20) NOT NULL,
    outcome       VARCHAR(4)  NOT NULL,
    attempts_used INT         NOT NULL,
    secret_number INT         NOT NULL,
    score         INT         NOT NULL,
    played_at     TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_game_id  UNIQUE (game_id),
    CONSTRAINT ck_outcome  CHECK (outcome IN ('WON', 'LOST')),
    CONSTRAINT ck_attempts CHECK (attempts_used BETWEEN 1 AND 10),
    CONSTRAINT ck_secret   CHECK (secret_number BETWEEN 1 AND 50),
    CONSTRAINT ck_score    CHECK (score BETWEEN 0 AND 100)
);
CREATE INDEX IF NOT EXISTS idx_results_played_at ON game_results (played_at DESC);
