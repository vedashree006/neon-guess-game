-- Privacy-conscious analytics, consent log and admin audit log.
-- All timestamps are UTC epoch milliseconds (BIGINT) so bucketing is portable and timezone-proof.
-- No IP addresses, user agents or personal data are stored anywhere in these tables.

-- One row per anonymous browser that accepted analytics cookies (random id from the neon_vid cookie).
CREATE TABLE IF NOT EXISTS analytics_visitors (
    visitor_id    VARCHAR(32) NOT NULL PRIMARY KEY,
    first_seen_ms BIGINT      NOT NULL,
    last_seen_ms  BIGINT      NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_visitors_first_seen ON analytics_visitors (first_seen_ms);
CREATE INDEX IF NOT EXISTS idx_visitors_last_seen ON analytics_visitors (last_seen_ms);

-- A visit = a run of activity by one visitor, closed after the inactivity timeout.
CREATE TABLE IF NOT EXISTS analytics_visits (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visitor_id       VARCHAR(32) NOT NULL,
    started_ms       BIGINT      NOT NULL,
    last_activity_ms BIGINT      NOT NULL,
    ended_ms         BIGINT,
    end_reason       VARCHAR(20),
    CONSTRAINT fk_visits_visitor FOREIGN KEY (visitor_id)
        REFERENCES analytics_visitors (visitor_id) ON DELETE CASCADE,
    CONSTRAINT ck_visits_reason CHECK (end_reason IS NULL OR end_reason IN ('TIMEOUT'))
);
CREATE INDEX IF NOT EXISTS idx_visits_visitor_open ON analytics_visits (visitor_id, ended_ms);
CREATE INDEX IF NOT EXISTS idx_visits_activity ON analytics_visits (ended_ms, last_activity_ms);
CREATE INDEX IF NOT EXISTS idx_visits_started ON analytics_visits (started_ms);

-- One row per page load. event_id is a client-generated random UUID: replays are ignored.
CREATE TABLE IF NOT EXISTS analytics_page_views (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   VARCHAR(36) NOT NULL,
    visit_id   BIGINT      NOT NULL,
    visitor_id VARCHAR(32) NOT NULL,
    path       VARCHAR(100) NOT NULL,
    viewed_ms  BIGINT      NOT NULL,
    CONSTRAINT uq_page_view_event UNIQUE (event_id),
    CONSTRAINT fk_pv_visit FOREIGN KEY (visit_id) REFERENCES analytics_visits (id) ON DELETE CASCADE,
    CONSTRAINT fk_pv_visitor FOREIGN KEY (visitor_id)
        REFERENCES analytics_visitors (visitor_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_pv_viewed ON analytics_page_views (viewed_ms);

-- Game lifecycle events written by the server (not the browser). Unique per game and type.
-- visitor_id is set to NULL (anonymised) if the visitor withdraws consent.
CREATE TABLE IF NOT EXISTS game_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id     VARCHAR(36) NOT NULL,
    event_type  VARCHAR(8)  NOT NULL,
    attempts    INT,
    visitor_id  VARCHAR(32),
    occurred_ms BIGINT      NOT NULL,
    CONSTRAINT uq_game_event UNIQUE (game_id, event_type),
    CONSTRAINT ck_game_event_type CHECK (event_type IN ('STARTED', 'WON', 'LOST')),
    CONSTRAINT ck_game_event_attempts CHECK (attempts IS NULL OR attempts BETWEEN 1 AND 10),
    CONSTRAINT fk_ge_visitor FOREIGN KEY (visitor_id)
        REFERENCES analytics_visitors (visitor_id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_game_events_time ON game_events (occurred_ms);

-- Append-only proof of the consent choices (random consent_id from the consent cookie, no identity).
CREATE TABLE IF NOT EXISTS consent_log (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consent_id          VARCHAR(36) NOT NULL,
    policy_version      INT         NOT NULL,
    analytics_allowed   BOOLEAN     NOT NULL,
    preferences_allowed BOOLEAN     NOT NULL,
    decided_ms          BIGINT      NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_consent_decided ON consent_log (decided_ms);
CREATE INDEX IF NOT EXISTS idx_consent_id ON consent_log (consent_id);

-- Security audit trail for the admin area (event and time only; no IP address, no typed usernames).
CREATE TABLE IF NOT EXISTS admin_audit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type  VARCHAR(20) NOT NULL,
    username    VARCHAR(64),
    occurred_ms BIGINT      NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_time ON admin_audit (occurred_ms);
