package com.vedashree.game;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.vedashree.game.Database.ScoreRecord;
import com.vedashree.game.Database.Sort;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.Test;

/** Schema migrations: idempotent, create every table, and never touch existing leaderboard data. */
class DatabaseMigrationTest {
    private static Database newDatabase() {
        return new Database("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
    }

    @Test
    void scriptSplitterDropsCommentsAndEmptyStatements() {
        List<String> statements = Migrator.statements("-- comment\nCREATE TABLE a (x INT);\n\n-- more\nCREATE INDEX i ON a (x);\n");
        assertEquals(2, statements.size());
        assertEquals("CREATE TABLE a (x INT)", statements.get(0));
    }

    @Test
    void migrationsCreateAllTablesAndAreRecorded() throws SQLException {
        Database database = newDatabase();
        database.init();
        try (Connection c = database.openConnection()) {
            assertEquals(List.of("V1__game_results.sql", "V2__analytics.sql"), Migrator.appliedScripts(c));
            for (String table : new String[] {"GAME_RESULTS", "ANALYTICS_VISITORS", "ANALYTICS_VISITS",
                    "ANALYTICS_PAGE_VIEWS", "GAME_EVENTS", "CONSENT_LOG", "ADMIN_AUDIT", "SCHEMA_VERSION"}) {
                try (Statement st = c.createStatement();
                     ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES "
                             + "WHERE TABLE_NAME = '" + table + "'")) {
                    rs.next();
                    assertEquals(1, rs.getInt(1), table);
                }
            }
        }
    }

    @Test
    void runningInitAgainChangesNothingAndKeepsExistingScores() throws SQLException {
        Database database = newDatabase();
        database.init();
        database.saveResult(new ScoreRecord(UUID.randomUUID().toString(), "Veda", "WON", 3, 25, 80, null));
        database.init();
        database.init();
        assertEquals(1, database.findResults(10, Sort.RECENT).size());
        try (Connection c = database.openConnection()) {
            assertEquals(2, Migrator.appliedScripts(c).size());
        }
    }

    @Test
    void anOldDatabaseWithOnlyTheOriginalTableIsUpgradedInPlace() throws SQLException {
        Database database = newDatabase();
        try (Connection c = database.openConnection(); Statement st = c.createStatement()) {
            // The exact original (pre-analytics) schema plus one saved game.
            st.execute("CREATE TABLE game_results (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "game_id VARCHAR(36) NOT NULL, player_name VARCHAR(20) NOT NULL, outcome VARCHAR(4) NOT NULL, "
                    + "attempts_used INT NOT NULL, secret_number INT NOT NULL, score INT NOT NULL, "
                    + "played_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, CONSTRAINT uq_game_id UNIQUE (game_id))");
            st.execute("INSERT INTO game_results (game_id, player_name, outcome, attempts_used, secret_number, score) "
                    + "VALUES ('old-game', 'Legacy', 'WON', 4, 7, 70)");
        }
        database.init();
        List<ScoreRecord> rows = database.findResults(10, Sort.RECENT);
        assertEquals(1, rows.size());
        assertEquals("Legacy", rows.get(0).playerName());
        assertTrue(database.stats().wins() == 1);
    }
}
